var CONFIG = { enabled: true }

function apply(ctx, config) {
    var cfg = Object.assign({}, CONFIG, config || {})
    if (cfg.enabled === false)
        return
    var locale = ctx.get('locale')
    if (locale === undefined || typeof locale.register !== 'function')
        return
    var namespaces = Object.keys(TRANSLATIONS)
    for (var i = 0; i < namespaces.length; i++) {
        var ns = namespaces[i]
        try {
            locale.register(ns, { ru: TRANSLATIONS[ns] })
        }
        catch (err) {
            var msg = String(err)
            // A namespace may already carry a Russian dictionary from another
            // plugin: that is not an error.
            if (msg.indexOf('already has locale') === -1)
                console.log('[dsh-local-ru] ' + ns + ': ' + msg)
        }
    }
}

window.__ModuleLoader__.load({
    id: 'dsh-local-ru',
    factory(require) {
        var module = { exports: {} }
        module.exports = { apply: apply, inject: ['locale'], TRANSLATIONS: TRANSLATIONS }
        return module.exports
    },
})
